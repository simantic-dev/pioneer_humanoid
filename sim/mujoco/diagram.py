# Draws sim/screenshots/lockstep-diagram.png: the arm scenario's parts (from `sim graph --scenario sim/scenario-arm.yaml`)
# with the per-tick data flow of sim/peers/arm_plant.py. Run: python sim/mujoco/diagram.py
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch
fig, ax = plt.subplots(figsize=(12, 6.2), dpi=110); ax.set_xlim(0, 12); ax.set_ylim(0, 6.2); ax.axis("off")
def box(x, y, w, h, text, fc, ec="#333", fs=9, bold=False, ls="-", z=2):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.08", fc=fc, ec=ec, lw=1.2, ls=ls, zorder=z))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs, weight="bold" if bold else "normal", zorder=z + 1)
def arrow(a, b, text="", both=False, off=(0, 0.13), color="#222", ha="center"):
    ax.annotate("", xy=b, xytext=a, arrowprops=dict(arrowstyle="<->" if both else "->", color=color, lw=1.3), zorder=5)
    if text: ax.text((a[0] + b[0]) / 2 + off[0], (a[1] + b[1]) / 2 + off[1], text, ha=ha, fontsize=8, zorder=6)
box(0.15, 0.25, 11.7, 5.8, "", "#fafafa", ls="--", z=0); ax.text(0.3, 5.82, "one `sim` process, one virtual clock (no wall-clock pacing)", fontsize=10, weight="bold", va="center")
box(0.4, 0.55, 3.95, 4.95, "", "#eef3fb", z=1); ax.text(0.55, 5.28, "simulated STM32G474 (the firmware runs here)", fontsize=9, weight="bold", va="center")
ax.plot([0.85, 0.85], [1.15, 4.3], color="#555", lw=1.5, zorder=1)
for y in (1.15, 2.1, 3.25, 4.3): ax.plot([0.85, 1.15], [y, y], color="#555", lw=1.5, zorder=1)
box(1.15, 3.85, 3.0, 0.95, "Joint firmware\nSimpleFOC angle loop\n(patched build)", "#dbe7fa", bold=True)
box(1.15, 2.85, 3.0, 0.8, "TIM4 registers CCR1/2/4, ARR\n(25 kHz PWM, firmware writes duty)", "#fff")
box(1.15, 1.75, 3.0, 0.7, "SPI1 (reads the encoder)", "#fff")
box(1.15, 0.85, 3.0, 0.6, "FDCAN2 (polls for commands)", "#fff")
arrow((2.65, 3.85), (2.65, 3.65))
box(5.75, 3.35, 2.6, 1.1, "arm_plant.py\nperipheral peer, ticks\nevery 40 us", "#fde9cf", bold=True)
box(5.75, 2.55, 2.6, 0.55, "pmsm.MOTOR: hinge angle, speed", "#fff", fs=8.5)
box(5.75, 1.75, 2.6, 0.7, "mt6835_peer.py\nSPI slave: the encoder", "#fff")
box(5.75, 0.85, 2.6, 0.6, "can_peer_arm.py: CAN master", "#fff")
box(9.55, 3.35, 2.15, 1.1, "MuJoCo 4.0.1\narm.xml: one hinge,\ngravity, inertia", "#dff3e3", bold=True)
arrow((4.15, 3.5), (5.75, 3.5), "1. bus_read of CCR/ARR", off=(0, 0.14))
arrow((8.35, 4.15), (9.55, 4.15), "2. torque\n(data.ctrl)", off=(0, 0.1))
arrow((9.55, 3.62), (8.35, 3.62), "3. qpos,\nqvel", off=(0, -0.42))
arrow((7.05, 3.35), (7.05, 3.1), "4. publish", off=(0.1, 0), ha="left")
arrow((7.05, 2.55), (7.05, 2.45))
arrow((4.15, 2.1), (5.75, 2.1), "21-bit angle + CRC8", both=True)
arrow((4.15, 1.15), (5.75, 1.15), "0x123 target / status", both=True, off=(0, 0.17))
ax.text(8.95, 2.95, "Each 40 us tick (one PWM period):\n 1. read the duty the firmware wrote\n 2. motor equations -> mean torque\n 3. mj_step(40 us) moves the arm\n 4. publish the angle for the encoder\n\nThe firmware's SPI read gets the angle\nfrom the last tick (0 to 40 us old).\nMuJoCo runs inside the peer's callback,\nso it shares the virtual clock.", fontsize=7.4, va="top", family="monospace")
fig.tight_layout(); fig.savefig("sim/screenshots/lockstep-diagram.png"); print("ok")
